/* --- stream/ngx_http_waf_frame.c ------------------------------------------
 *
 * Фаза кадров: собственный обработчик апгрейженного соединения вместо
 * ngx_http_upstream_process_upgraded(). Оба направления, только gate, один
 * кадр в полёте на соединение, единица инспекции -- кадр как пришёл (сборки
 * фрагментов нет); подмена полезной нагрузки по секции rewrite.
 */

#define NGX_HTTP_WAF_AUDIT_FRAMES_OFF   0
#define NGX_HTTP_WAF_AUDIT_FRAMES_DENY  1
#define NGX_HTTP_WAF_AUDIT_FRAMES_ALL   2

/* Кадр в записи аудита: то, чего у запроса нет. Заполняется кадром в полёте. */
typedef struct {
    u_char                    *conn_id;      /* ray рукопожатия, hex     */
    ngx_str_t                 *direction;    /* c2s | s2c                */
    ngx_str_t                 *opcode;
    uint64_t                   seq;
    size_t                     size;         /* полезная нагрузка, байт  */
    u_char                    *payload;      /* без маски, пул кадра     */
    ngx_uint_t                 fragments;    /* из скольких кадров собран */
    unsigned                   fin:1;
    unsigned                   rewritten:1;
    unsigned                   cached:1;     /* вердикт из кеша по хешу  */
} ngx_http_waf_frame_audit_t;

/* Итог соединения для записи phase=session при закрытии. */
typedef struct {
    u_char                    *conn_id;
    uint64_t                   frames_c2s;
    uint64_t                   frames_s2c;
    off_t                      bytes_c2s;
    off_t                      bytes_s2c;
    uint64_t                   denied;
    uint64_t                   rewritten;
    uint64_t                   cached;         /* вердиктов из кеша        */
    uint64_t                   reassembled;    /* сообщений из фрагментов  */
    uint64_t                   control_dropped; /* ping/pong сверх частоты */
    ngx_uint_t                 close_code;
    const char                *close_reason; /* peer|waf_deny|timeout|error */
    const char                *close_why;    /* строка лога                */
    ngx_msec_t                 duration_ms;
} ngx_http_waf_session_audit_t;

