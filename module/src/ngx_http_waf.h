/* --- архивация объектов обменника --------------------------------------------
 *
 * Объект, названный в waf_archive, модуль из обменника не удаляет: владение
 * ключом переходит агенту, и он же его вычистит, переложив содержимое в архив
 * и подменив локатор в записи аудита. Без этого запись уносила бы ключ, по
 * которому уже ничего не достать: удаление происходит до её сборки.
 *
 * Набор -- маска по ngx_http_waf_obj_e с той же трёхзначностью, что у
 * waf_capture: NGX_CONF_UNSET_UINT -- "здесь не задано", наследуем родителя;
 * 0 -- явное none, наследование останавливает.
 *
 * Срок, исходы и предел записи привязаны к объекту, а не к набору: строка
 * директивы настраивает только названные в ней виды, и строки одного уровня
 * складываются. Иначе назвать телу свой размер (body=8k) значило бы
 * переписать заодно и заголовки.
 *
 * Архив ничьего разрешения не спрашивает. Названный здесь объект снимается и
 * уезжает агенту независимо от waf_capture и от needs= инспекторов: это не
 * инспекция, а требование хранить, и отказать ему может только абсолютный
 * предел чтения (waf_body_limit, client_max_body_size, max= обменника).
 * В сообщение инспекторам архив не добавляет.
 */

/* Исходы, на которых объект сохраняется: биты по ngx_http_waf_verdict_e. */
#define NGX_HTTP_WAF_ARCHIVE_WHEN_ALL                                          \
    ((1u << NGX_HTTP_WAF_V_ALLOW) | (1u << NGX_HTTP_WAF_V_REDIRECT)            \
     | (1u << NGX_HTTP_WAF_V_DENY))

/*
 * Срок хранения в архиве, секунды. Едет на проводе и становится тегом объекта,
 * по которому бакет применяет lifecycle-правило. Ноль -- "хранить вечно":
 * отсутствие срока это решение оператора, а не пропуск, и означать нулевое
 * время оно не может.
 */
#define NGX_HTTP_WAF_ARCHIVE_TTL_FOREVER  0

/*
 * Предел записи в архив, размер на объекте (body=8k). Ноль -- "весь объект":
 * архив забирает столько, сколько модуль прочитал. Режет агент, а не модуль:
 * в обменнике объект лежит целиком, потому что его мог попросить инспектор.
 */
#define NGX_HTTP_WAF_ARCHIVE_LIMIT_WHOLE  0

/*
 * Предел объекта для инспекторов, размер на объекте (body=128k). Ноль --
 * весь объект, сколько модуль прочитал. Это потолок волны, не архива:
 * архив и превью этой оси не подчинены.
 */
#define NGX_HTTP_WAF_CAPTURE_LIMIT_WHOLE  0

/*
 * reload <obj>=capture -- размер как у capture. Не 0: ноль уже значит
 * «весь объект». Не (size_t)-1: это NGX_CONF_UNSET_SIZE.
 */
#define NGX_HTTP_WAF_RELOAD_LIMIT_CAPTURE  ((size_t) -2)


