// Чтение числовых параметров из окружения.
//
// Отдельный модуль ради одной проверки: Number("0,05") в JavaScript возвращает
// NaN, а не ошибку. Дальше NaN ведёт себя тихо и разрушительно -- любое
// сравнение с ним ложно, поэтому доля трафика, заданная с запятой, означает не
// «неверная доля», а «этой ветки трафика не будет вовсе». Прогон при этом
// проходит, отчёт выглядит здоровым, и ошибка обнаруживается только по
// отсутствию строк в сводке.
//
// Запятая появляется сама: PowerShell форматирует [double] по текущей локали,
// и на русской системе 0.05 превращается в "0,05". scripts/run.ps1 приводит
// числа к инвариантной культуре, но полагаться только на это нельзя -- значения
// приходят ещё из .env и из окружения оболочки.

export function envNum(name, dflt) {
    const raw = __ENV[name];

    if (raw === undefined || raw === '') {
        return dflt;
    }

    if (String(raw).indexOf(',') >= 0) {
        throw new Error(
            `${name}="${raw}": десятичный разделитель -- точка, а не запятая. ` +
            `Значение с запятой JavaScript читает как NaN, и параметр молча ` +
            `перестаёт действовать.`);
    }

    const v = Number(raw);

    if (!isFinite(v)) {
        throw new Error(`${name}="${raw}": не число`);
    }

    return v;
}
